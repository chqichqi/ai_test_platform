"""文本归一化工具——探索侧/校正侧/执行侧共用。

背景（2026-08-23 真机实证）：应用侧文本可能带空格（按钮文案渲染为「重 置」、
「登 录」），而用例/需求文本是「重置」「登录」——Playwright get_by_text 子串
匹配会因空格失败。各处文本比较（探索评分/匹配、校正判断）前统一去空白，
避免精确/子串匹配因内部空白失配。
"""

import re

# 空白集合：普通空白（空格/换行/制表等）+ 全角空格 U+3000
_WS_RE = re.compile(r"[\s　]+")


def normalize_ws(s) -> str:
    """去除所有空白（空格/换行/制表/全角空格），返回归一化文本。"""
    if not s:
        return ""
    return _WS_RE.sub("", str(s))
